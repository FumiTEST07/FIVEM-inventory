--- as-evidencestash / 押収品倉庫
--- ServerConfig : サーバーのみが読み込む設定。
--- 容量・クールダウン・検証の厳しさなど「正」となる値はすべてここにあります。
--- client_scripts には含めていないため、クライアントからは参照できません。

ServerConfig = {}

-----------------------------------------------------------------------------
-- stash の容量
-- 要件どおりの値。ox_inventory:RegisterStash に渡されます。
-----------------------------------------------------------------------------

--- スロット数
ServerConfig.slots = 100

--- 最大重量 (ox_inventory の単位: グラム)
ServerConfig.maxWeight = 500000

-----------------------------------------------------------------------------
-- 検証
-----------------------------------------------------------------------------

--- 距離検証の許容誤差 (m)。
--- サーバーが持つプレイヤー座標はネットワーク同期の遅延で数メートルずれるため、
--- SharedConfig の操作距離にこの値を加えた範囲まで許可します。
--- 小さくしすぎると正常な操作が弾かれ、大きくしすぎると遠隔操作を許してしまいます。
--- [AI提案] 3.0m
ServerConfig.distanceTolerance = 3.0

--- true にすると、オンデューティ (勤務中) のプレイヤーのみ利用できます。
--- [AI提案] 元の要件に指定がなかったため、既定は false (勤務状態を問わない)。
--- 勤務管理を厳格に運用しているサーバーでは true を推奨します。
ServerConfig.requireOnDuty = false

--- 連続で開く操作のクールダウン (秒)。0 で無効。
--- 元の要件では「クールダウン: 未設定」でしたが、セキュリティ要件に
--- 「クールダウン検証」があったため、設定可能な形で実装し既定は無効にしています。
--- イベント連打による負荷を抑えたい場合は 2〜5 秒程度を推奨します。
ServerConfig.cooldownSeconds = 0

-----------------------------------------------------------------------------
-- 監査ログ
-- アイテムそのものは ox_inventory が自身の DB に永続化します。
-- ここで記録するのは「誰が・いつ・どの倉庫にアクセスしたか」の履歴です。
-----------------------------------------------------------------------------

ServerConfig.logging = {
    --- ログ記録を有効にするか
    enabled = true,

    --- テーブル名
    tableName = 'as_evidencestash_logs',

    --- リソース起動時に CREATE TABLE IF NOT EXISTS を実行するか。
    --- sql/install.sql を手動で流す運用にする場合は false にしてください。
    autoCreateTable = true,

    --- 拒否 (権限不足・距離外など) も記録するか。
    --- 不正アクセスの兆候を追えるので有効を推奨します。
    logDenied = true,

    --- 倉庫を閉じたタイミングも記録するか (滞在時間の把握に使えます)。
    logClose = true,

    --- ログの保持日数。0 で無期限。
    --- 1 以上にすると、リソース起動時に古いログを削除します。
    retentionDays = 90
}

-----------------------------------------------------------------------------
-- デバッグ
-----------------------------------------------------------------------------

--- true にすると検証の経過をサーバーコンソールに出力します。
--- 本番環境では false にしてください。
ServerConfig.debug = false
