--- as-evidencestash / 押収品倉庫
--- ClientConfig : 見た目と入力に関する設定のみ。
--- ここにある値はクライアントが書き換え可能なため、
--- 権限・距離・数量などの判定材料として使ってはいけません。

ClientConfig = {}

-----------------------------------------------------------------------------
-- 操作キー
-----------------------------------------------------------------------------

--- 倉庫を開くキー (デフォルト: 38 = E)。
--- 参考: https://docs.fivem.net/docs/game-references/controls/
ClientConfig.openControl = 38

-----------------------------------------------------------------------------
-- TextUI (ox_lib)
-----------------------------------------------------------------------------

ClientConfig.textUI = {
    --- 表示位置: 'left-center' | 'right-center' | 'top-center'
    position = 'left-center',
    --- アイコン (Font Awesome)
    icon = 'box-archive',
    --- アイコン色 (ox_lib のカラーキー)
    iconColor = '#c1c1c1'
}

-----------------------------------------------------------------------------
-- 通知 (ox_lib)
-----------------------------------------------------------------------------

ClientConfig.notify = {
    position = 'top-right',
    duration = 5000
}

-----------------------------------------------------------------------------
-- 監視ループ
-- 距離判定のためのループ間隔 (ms)。数値を下げると反応が良くなり、
-- 上げると負荷が下がります。
-----------------------------------------------------------------------------

ClientConfig.loop = {
    --- 全ての倉庫から離れているとき
    idleInterval = 1000,
    --- いずれかの倉庫の近く (checkRadius 以内) にいるとき
    nearInterval = 250,
    --- 「近く」と判定する半径 (m)。操作距離より十分大きくします。
    checkRadius = 25.0
}

-----------------------------------------------------------------------------
-- ブリップ
-- SharedConfig.stashes の showBlip = true の倉庫にのみ作成されます。
-----------------------------------------------------------------------------

ClientConfig.blip = {
    enabled = true,
    sprite = 478,
    color = 38,
    scale = 0.7,
    display = 4,
    shortRange = true,
    label = '押収品倉庫'
}

-----------------------------------------------------------------------------
-- 権限による事前フィルタ (UX 目的のみ)
-----------------------------------------------------------------------------

--- true の場合、ジョブ条件を満たさないプレイヤーには TextUI を表示しません。
--- これは体験を良くするためだけの処理で、セキュリティ上の意味はありません。
--- 実際の許可判定は必ずサーバー側 (server/main.lua) が行います。
ClientConfig.hideTextUIWithoutJob = true
